import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';

// Only names and IDs may enter the browser bundle. Password configuration stays on the server.
export function publicCommunityDirectory(entries) {
  if (!Array.isArray(entries) || !entries.length) throw new Error('Add at least one community.');
  const ids = new Set();
  return entries.map((entry) => {
    if (
      typeof entry.id !== 'string' ||
      !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(entry.id) ||
      ids.has(entry.id)
    )
      throw new Error('Community IDs must be unique lowercase words separated by hyphens.');
    if (typeof entry.name !== 'string' || !entry.name.trim())
      throw new Error('Enter a community name.');
    for (const field of ['studentPassword', 'instructorPassword']) {
      const setting = entry[field];
      if (
        !setting ||
        typeof setting.env !== 'string' ||
        !/^[A-Z][A-Z0-9_]*$/.test(setting.env) ||
        setting.env.startsWith('NEXT_PUBLIC_')
      )
        throw new Error(`Community ${entry.id}: ${field} needs a private environment setting.`);
    }
    ids.add(entry.id);
    return { id: entry.id, name: entry.name.trim() };
  });
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const entries = JSON.parse(
    await readFile(new URL('../communitypasswords.json', import.meta.url), 'utf8'),
  );
  const directory = publicCommunityDirectory(entries);
  await writeFile(
    new URL('../src/lib/community-directory.ts', import.meta.url),
    await format(
      '// Generated by scripts/sync-communities.mjs. Edit communitypasswords.json instead.\n' +
        `export const schoolCommunities = ${JSON.stringify(directory, null, 2)} as const;\n`,
      { parser: 'typescript', singleQuote: true, trailingComma: 'all', printWidth: 100 },
    ),
  );
}
